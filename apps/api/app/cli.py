"""Maintenance commands.  Usage: ``python -m app.cli <command>``."""

import argparse
import json
import sys
from pathlib import Path

from sqlalchemy.schema import CheckConstraint

import app.models  # noqa: F401  (registers every table on Base.metadata)
from app.db.base import Base
from app.db.session import get_session_factory
from app.main import create_app
from app.seeds.topics import seed_topics


def _seed_topics() -> int:
    with get_session_factory()() as session:
        count = seed_topics(session)
    print(f"Seeded {count} canonical topics.")
    return 0


def _export_openapi(path: str) -> int:
    schema = create_app().openapi()
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(schema, indent=2, sort_keys=True) + "\n")
    print(f"Wrote {target}")
    return 0


def describe_schema() -> str:
    """Markdown reference of every table, generated from the models (never hand-maintained)."""
    lines = [
        "Generated by `python -m app.cli describe-schema` from the SQLAlchemy models. "
        "`TIMESTAMPTZ` columns are shown as `DATETIME` below and are always stored in UTC.",
        "",
    ]
    for name in sorted(Base.metadata.tables):
        table = Base.metadata.tables[name]
        lines += [f"### `{name}`", "", "| Column | Type | Notes |", "|---|---|---|"]
        for column in table.columns:
            notes: list[str] = []
            if column.primary_key:
                notes.append("PK")
            for fk in column.foreign_keys:
                action = fk.ondelete or "NO ACTION"
                notes.append(f"FK to `{fk.column.table.name}.{fk.column.name}` ({action})")
            if column.nullable and not column.primary_key:
                notes.append("NULL")
            if column.server_default is not None:
                default = str(getattr(column.server_default, "arg", "")).replace("|", "\\|")
                notes.append(f"default `{default}`")
            lines.append(f"| `{column.name}` | `{column.type}` | {'; '.join(notes)} |")
        checks = [c for c in table.constraints if isinstance(c, CheckConstraint)]
        if checks:
            lines += ["", "**Checks:** " + "; ".join(f"`{c.sqltext}`" for c in checks)]
        if table.indexes:
            indexes = sorted(table.indexes, key=lambda i: i.name or "")
            described = [f"`{i.name}`" + (" (unique)" if i.unique else "") for i in indexes]
            lines += ["", "**Indexes:** " + "; ".join(described)]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.cli")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("seed-topics", help="Idempotently insert/update the canonical topics")
    sub.add_parser("describe-schema", help="Print a Markdown reference of every table")
    export = sub.add_parser("export-openapi", help="Write the OpenAPI schema to a file")
    export.add_argument("path", help="Destination file, e.g. ../../packages/shared/openapi.json")
    args = parser.parse_args(argv)
    if args.command == "seed-topics":
        return _seed_topics()
    if args.command == "describe-schema":
        print(describe_schema())
        return 0
    return _export_openapi(args.path)


if __name__ == "__main__":
    sys.exit(main())
